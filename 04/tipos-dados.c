#include <stdio.h>

// função principal - tudo que está aqui dentro será interpretado
int main(){
    int idade = 21; // número inteiro
    float altura = 1.75; // número decimal
    char inicial = 'C'; // caractere

    printf("Idade: %d\n", idade);
    printf("Altura: %f\n", altura);
    printf("Inicial de Carlos: %c\n", inicial);

    return 0; // retorno do tipo int
}
